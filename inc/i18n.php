function localized_text(array $record, string $field): string {
    $language = $_SESSION['language'] ?? 'en';
    $localizedField = $language === 'bn' || $language === 'hi' ? $field . '_' . $language : $field;
    $value = $record[$localizedField] ?? '';
    return $value !== '' ? (string)$value : (string)($record[$field] ?? '');
}
